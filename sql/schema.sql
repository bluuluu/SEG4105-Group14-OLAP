CREATE TABLE IF NOT EXISTS dim_date (
    date_key integer PRIMARY KEY,
    full_date date NOT NULL UNIQUE,
    year smallint NOT NULL,
    quarter smallint NOT NULL CHECK (quarter BETWEEN 1 AND 4),
    month smallint NOT NULL CHECK (month BETWEEN 1 AND 12)
);

CREATE TABLE IF NOT EXISTS dim_product (
    product_key integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id varchar(40) NOT NULL UNIQUE,
    product_name varchar(150) NOT NULL,
    category varchar(80) NOT NULL
);

CREATE TABLE IF NOT EXISTS dim_store (
    store_key integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    store_id varchar(40) NOT NULL UNIQUE,
    store_name varchar(150) NOT NULL,
    region varchar(80) NOT NULL
);

CREATE TABLE IF NOT EXISTS fact_sales (
    sales_line_key bigint PRIMARY KEY,
    date_key integer NOT NULL REFERENCES dim_date,
    store_key integer NOT NULL REFERENCES dim_store,
    product_key integer NOT NULL REFERENCES dim_product,
    quantity_sold integer NOT NULL CHECK (quantity_sold >= 0),
    net_sales_amount numeric(14, 2) NOT NULL CHECK (net_sales_amount >= 0)
);

CREATE TABLE IF NOT EXISTS fact_inventory_snapshot (
    inventory_snapshot_key bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    date_key integer NOT NULL REFERENCES dim_date,
    store_key integer NOT NULL REFERENCES dim_store,
    product_key integer NOT NULL REFERENCES dim_product,
    stock_on_hand integer NOT NULL CHECK (stock_on_hand >= 0),
    reorder_point integer NOT NULL CHECK (reorder_point >= 0),
    UNIQUE (date_key, store_key, product_key)
);

CREATE INDEX IF NOT EXISTS sales_date_idx ON fact_sales (date_key);
CREATE INDEX IF NOT EXISTS sales_store_date_idx ON fact_sales (store_key, date_key);
CREATE INDEX IF NOT EXISTS sales_product_date_idx ON fact_sales (product_key, date_key);
CREATE INDEX IF NOT EXISTS inventory_store_date_idx ON fact_inventory_snapshot (store_key, date_key);
CREATE INDEX IF NOT EXISTS inventory_product_date_idx ON fact_inventory_snapshot (product_key, date_key);

CREATE TABLE IF NOT EXISTS etl_run (
    run_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    batch_id text NOT NULL,
    started_at timestamptz NOT NULL DEFAULT clock_timestamp(),
    finished_at timestamptz,
    status text NOT NULL DEFAULT 'running'
        CHECK (status IN ('running', 'loaded', 'loaded_with_rejects', 'failed')),
    summary jsonb NOT NULL DEFAULT '{}',
    error text
);

CREATE INDEX IF NOT EXISTS etl_run_batch_idx ON etl_run (batch_id, run_id DESC);

CREATE TABLE IF NOT EXISTS etl_reject (
    run_id bigint NOT NULL REFERENCES etl_run,
    source_file text NOT NULL,
    line_number integer NOT NULL,
    reason text NOT NULL,
    source_row jsonb NOT NULL,
    PRIMARY KEY (run_id, source_file, line_number)
);

CREATE TABLE IF NOT EXISTS app_user (
    username text PRIMARY KEY,
    password_hash text NOT NULL,
    role text NOT NULL CHECK (role IN ('manager', 'admin')),
    enabled boolean NOT NULL DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS app_session (
    token_hash text PRIMARY KEY,
    username text NOT NULL REFERENCES app_user,
    expires_at timestamptz NOT NULL
);

CREATE INDEX IF NOT EXISTS app_session_user_idx ON app_session (username);
